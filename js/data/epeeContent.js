const packedScenarios = packedScenarioRows.map((scenario, index) => ({
  ...scenario,
  id: scenarioRows.length + index + 1,
  packTitle: scenarioPacks.find((pack) => pack.id === scenario.packId)?.title || "Scenario Pack",
  label: scenario.choices[scenario.correct],
  correctAction: scenario.choices[scenario.correct]
}));

export const scenarios = [...legacyScenarios, ...packedScenarios];

function actionThemeFromAction(action) {
  if (/Retreat|Hold|Advance|Half Step/i.test(action)) return "Distance Control";
  if (/Parry|Riposte|Beat|Disengage/i.test(action)) return "Blade Work";
  if (/Counter|Tempo|Rhythm/i.test(action)) return "Timing";
  if (/Feint|Bait|Second/i.test(action)) return "Tactical IQ";
  return "Decision Making";
}
